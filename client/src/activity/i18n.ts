/** Sunucudan gelen (her zaman Türkçe) kategori adını gösterim diline çevirir.
 *  Filtreleme/seçim mantığı hep orijinal Türkçe adı kullanır — bu yalnız etiket. */
export function categoryLabel(language: ActivityLanguage, name: string): string {
  if (language === 'tr') return name
  return CATEGORY_LABELS_EN[name] ?? name
}

export type Translate = (key: StringKey, params?: Record<string, string | number>) => string

export function translate(language: ActivityLanguage, key: StringKey, params?: Record<string, string | number>): string {
  const template = STRINGS[language][key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

interface I18nValue { language: ActivityLanguage; t: Translate }

// Varsayılan TR: sağlayıcı olmadan render edilen bir bileşen bile metinsiz kalmaz.
export const I18nContext = createContext<I18nValue>({
  language: 'tr',
  t: (key, params) => translate('tr', key, params),
})

export function useI18n(): I18nValue {
  return useContext(I18nContext)
}

/** Sayıları arayüz diline göre biçimler (ör. 12.400 / 12,400). */
export function formatNumber(language: ActivityLanguage, value: number): string {
  return value.toLocaleString(language === 'tr' ? 'tr-TR' : 'en-US')
}

/** Yüzde yazımı dile göre: Türkçede işaret önde ("%60"), İngilizcede sonda ("60%"). */
export function formatPercent(language: ActivityLanguage, value: number): string {
  return language === 'tr' ? `%${value}` : `${value}%`
}
